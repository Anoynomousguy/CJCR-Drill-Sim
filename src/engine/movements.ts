export const MOVEMENTS: MoveDef[] = [...footHalt, ...footMarch, ...rifle, ...colour];

export const MOVE_BY_TYPE: Record<string, MoveDef> = Object.fromEntries(
  MOVEMENTS.map((m) => [m.type, m]),
);

export function getMoveDef(type: string): MoveDef {
  const def = MOVE_BY_TYPE[type];
  if (!def) throw new Error(`Unknown movement type: ${type}`);
  return def;
}

export function defaultParams(type: string): Record<string, number | string> {
  const def = MOVE_BY_TYPE[type];
  return { ...(def?.defaults ?? {}) };
}

export function describeParams(type: string, params: Record<string, number | string>): string {
  const def = MOVE_BY_TYPE[type];
  if (!def) return '';
  const parts: string[] = [];
  for (const p of def.params ?? []) {
    const value = params[p.key] ?? def.defaults?.[p.key];
    if (value === undefined) continue;
    if (p.key === 'dir') parts.push(String(value));
    else parts.push(`${value} pace${Number(value) === 1 ? '' : 's'}`);
  }
  return parts.join(' · ');
}

