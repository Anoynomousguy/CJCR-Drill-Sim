import type { ColourState, Discipline, Eyes, Gait, HeadDress, Posture, Snapshot, Spacing, WeaponState } from './types';

export type MoveKind =
  | 'state'
  | 'turn'
  | 'pace'
  | 'march'
  | 'halt'
  | 'markTime'
  | 'changeStep'
  | 'dress'
  | 'eyes'
  | 'order'
  | 'wheel'
  | 'form'
  | 'fall'
  | 'saluteMarch';

export interface Effect {
  posture?: Posture;
  weapon?: WeaponState;
  colour?: ColourState;
  gait?: Gait;
  eyes?: Eyes;
  headdress?: HeadDress;
  spacing?: Spacing;
  step?: 'normal' | 'out' | 'short';
  stance?: 'attention' | 'present';
  turnDeg?: number;
  /** Required when the angle alone cannot express the side (180°). */
  turnDir?: 'right' | 'left';
}

export interface ParamDef {
  key: string;
  label: string;
  type: 'number' | 'select';
  min?: number;
  max?: number;
  step?: number;
  options?: { value: string; label: string }[];
}

export interface Requirement {
  weapon?: WeaponState[];
  colour?: ColourState[];
  posture?: Posture[];
  gait?: Gait[];
}

export interface MoveDef {
  type: string;
  discipline: Discipline;
  title: string;
  words: string;
  reference: string;
  kind: MoveKind;
  counts: number;
  effect?: Effect;
  params?: ParamDef[];
  defaults?: Record<string, number | string>;
  requires?: Requirement;
  help: string;
  scope?: 'all' | 'colourParty';
  dir?: 1 | -1;
}

